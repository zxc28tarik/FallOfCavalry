const BUILDING_INDEX = new Map(BUILDING_DEFS.map((def) => [def.id, def]));

export function listCityBuildingDefs() {
  return BUILDING_DEFS.map((def) => ({ ...def }));
}

export function getCityBuildingDef(id) {
  if (!id) return null;
  const def = BUILDING_INDEX.get(String(id));
  return def
    ? {
        ...def,
        bonuses: [...(def.bonuses || [])],
        penalties: [...(def.penalties || [])],
        services: [...(def.services || [])],
        compatibleSlotTags: [...(def.compatibleSlotTags || [])],
        synergyTags: [...(def.synergyTags || [])],
        factions: [...(def.factions || [])],
      }
    : null;
}

export function getCityBuildingLabel(id) {
  return getCityBuildingDef(id)?.name || String(id || 'Bina');
}

export function listCityBuildingsForService(serviceId) {
  return BUILDING_DEFS
    .filter((def) => Array.isArray(def.services) && def.services.includes(serviceId))
    .map((def) => ({ ...def }));
}

export function listInfrastructureBuildingIds() {
  return [...INFRASTRUCTURE_IDS];
}

export function isCityBuildingAllowedForFaction(def, factionId) {
  if (!def) return false;
  if (!Array.isArray(def.factions) || def.factions.length === 0) return true;
  return def.factions.includes(factionId);
}

export function isCityBuildingCompatibleWithSlot(def, slotTags = []) {
  if (!def) return false;
  const tags = Array.isArray(slotTags) ? slotTags : [];
  return (def.compatibleSlotTags || []).some((tag) => tags.includes(tag));
}
